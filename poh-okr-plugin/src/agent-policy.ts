/**
 * Правило записи задач, договорённостей и рисков для модели.
 *
 * Харнесс сам по себе не знает, куда девать результат разбора встречи, и модель выбирает
 * место сама: в живой сессии она сложила задачи в markdown-заметку нексуса, и в панели
 * «Управление целями» не появилось ничего — PO увидел это только по пустому дашборду.
 * Плагин отдаёт правило в системный промпт: раз раздел установлен, единственное хранилище —
 * Backlog.md, и запись идёт по тем же меткам, которые читает панель.
 *
 * Текст собирается из тех же констант, что и запись плагина: разъехаться названию метки
 * в промпте и в коде нельзя, иначе модель заведёт задачи, которых панель не увидит.
 */
import type { OkrConfig } from './config.js'
import { PO_TASK_KINDS, poTaskLabel, krLabel } from './model.js'

/** Системная секция: правило фиксации операционной работы PO. */
export function capturePolicy(config: OkrConfig): string {
  const kinds = PO_TASK_KINDS.map(kind => poTaskLabel(kind)).join(', ')
  return [
    '# Задачи, договорённости и риски Product Owner',
    '',
    'В этом воркспейсе установлен раздел «Управление целями» (poh-okr-plugin).',
    `Единственное хранилище задач, договорённостей и рисков — Backlog.md в ${config.workspaceRoot}.`,
    'Записывать их в markdown-файлы, заметки, нексусы или только в ответ чата — нельзя:',
    'в панель раздела попадает лишь то, что заведено задачей Backlog.md, остальное для PO',
    'не существует.',
    '',
    '## Когда записывать',
    '',
    'Разобрал встречу, транскрипт, переписку или беседу — сразу заводи найденное задачами,',
    'не спрашивая разрешения и не предлагая «оформить позже». Разрешения спрашивают только',
    'на удаление и на смену уже записанного чужого решения. В ответе перечисли заведённое',
    'с идентификаторами, чтобы PO видел, что попало в панель.',
    '',
    '## Как записывать',
    '',
    `Задача PO — задача Backlog.md типа \`${config.poTaskType}\` с меткой вида:`,
    '',
    `- \`${poTaskLabel('task')}\` — работа PO: сделать, написать, согласовать;`,
    `- \`${poTaskLabel('control')}\` — договорённость: кто-то что-то пообещал, нужен контроль;`,
    `- \`${poTaskLabel('risk')}\` — риск: что может помешать цели.`,
    '',
    'Вид задаётся только меткой — отдельных типов задач под договорённость и риск нет.',
    '',
    '```sh',
    `cd ${config.workspaceRoot}`,
    `${config.backlogBin} task create "<название одной строкой>" \\`,
    `  --type ${config.poTaskType} --labels ${poTaskLabel('control')}[,${krLabel('<id KR>')}] \\`,
    '  [--dep <id KR>] [--due-date ГГГГ-ММ-ДД] [--priority high|medium|low] \\',
    '  [--description "<контекст: кто сказал, откуда взято>"]',
    '```',
    '',
    'Привязка к ключевому результату пишется дважды и всегда вместе: метка',
    '`okr-kr:<id KR>` и зависимость `--dep <id KR>`. Метка нужна панели (список задач',
    'зависимостей не отдаёт), зависимость — сама связь.',
    '',
    'Срок ставь только тот, который назвали. Не назвали — задача без срока, выдумывать',
    'дату нельзя.',
    '',
    'Приоритет не выводится: ставь его, только если важность прозвучала словами —',
    '«срочно», «критично», «в первую очередь», «не горит», «потерпит». Тон беседы,',
    'близкий срок, размер последствий и порядок пунктов в заметках признаками важности',
    'не считаются. Не прозвучало — оставь задачу без приоритета: пустой приоритет',
    'означает «решает PO», а проставленный тобой выдаёт догадку за его решение.',
    '',
    '## Чего не делать',
    '',
    `- Не заводить свои типы задач и метки: панель читает только \`${kinds}\`.`,
    '- Не проставлять приоритет по догадке — см. выше: пусто лучше выдуманного.',
    `- Не создавать ключевые результаты и объективы вручную: KR — задача типа \`${config.krTaskType}\`,`,
    '  объектив — milestone, их ведёт пайплайн `/okr-*`.',
    '- Не править файлы `backlog/tasks/*.md` напрямую: единственный писатель — CLI, он',
    '  держит метаданные в согласованном состоянии.',
    '- Перед созданием свериться с уже заведённым:',
    `  \`${config.backlogBin} task list --type ${config.poTaskType} --plain\`, чтобы не плодить дубли.`,
  ].join('\n')
}
